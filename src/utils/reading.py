"""固有名詞の読み（TTS 用）。

なぜ必要か
----------
`ja-JP-NanamiNeural` は日本語のボイスなので、ラテン文字の語を日本語話者の
標準的な読みで発音する保証がない。実測（2026-08-22 生成のショート）では
``Claude`` の読みが明らかにおかしく、動画の品質を落としていた。ニュースの
題材が AI なので製品名・企業名は**必ず**ナレーションに出てくる。

**辞書は「読みを指定する」ためだけに使い、字幕には一切適用しない。**
画面には ``Claude`` と表示され、音声では「クロード」と読まれるのが正しい。
カタカナに置き換えた文字列を字幕に流すと、原綴りを知りたい視聴者から
情報を奪う。適用箇所を `VoiceGenerator` の SSML 組み立てに閉じているのが
その担保で、`RemotionRenderer` は `Script.segment_narrations` を素で使う。

なぜ SSML の ``<sub alias>`` ではなく素の置換か
----------------------------------------------
``<sub>`` でも同じことはできるが、SSML はセグメント境界の ``<bookmark>`` を
埋め込んだ文字列を XML エスケープしてから組み立てている。そこにタグを
差し込むと、エスケープの順序（先に置換してからエスケープするのか、
エスケープ済みの文字列にタグを入れるのか）を間違えやすい。素の置換なら
**エスケープ前の平文に対する操作**として閉じ、単体テストで文字列を突き合わせる
だけで検証できる。読み上げ結果は同じである。

辞書に足すときの規約
--------------------
**実際に聞いて間違っていた語だけを足す。** 「間違いそうだから」で足すと、
Azure 側が正しく読めている語を不自然なカタカナに落とす方向に外れうる。
`AI` / `API` / `GPT` を入れていないのはこの理由（実測で問題が出ていない）。
"""

from __future__ import annotations

import re

# 語 → 読み（カタカナ）。
#
# **英数字に挟まれた位置ではマッチさせない**（`_PATTERN` の前後読み）。
# 「Claudeの」は置換したいが、仮に `Claudette` のような語が来たときに
# 「クロードtte」にはしたくない。日本語の助詞（の・は・が）はラテン文字では
# ないので、`Claudeの` は問題なくマッチする。
READINGS: dict[str, str] = {
    # 2026-08-22 の生成物で実際に読みが崩れていた語。
    "Claude": "クロード",
    # 上と同じ記事に登場し、同じ理由で崩れうる（英語の綴りが長く、
    # 日本語話者の標準読みが綴りから自明でない）。
    "Anthropic": "アンソロピック",
    "Gemini": "ジェミニ",
    "OpenAI": "オープンエーアイ",
    "Azure": "アジュール",
    "Copilot": "コパイロット",
}


def _build_pattern(terms: dict[str, str]) -> re.Pattern[str]:
    """辞書の全語を1つの正規表現にまとめる。

    **長い語を先に並べる。** `re` の `|` は左から最初にマッチしたものを採るため、
    将来 `Claude Code` のような複合語を足したときに `Claude` が先にあると
    複合語側が一度もマッチしない（`Claude` + ` Code` に割れる）。

    **選択肢は必ず `(?:...)` で囲む。** `|` は正規表現で最も結合が弱いので、
    囲まないと前後の境界条件が**最初と最後の選択肢にしか掛からない**。
    実際に踏んだ: 囲み忘れた版は `Claudette` を「クロードtte」に変えていた
    （`Claude` は中間の選択肢で、後読みが効いていなかった）。
    """
    alternatives = "|".join(re.escape(t) for t in sorted(terms, key=len, reverse=True))
    return re.compile(rf"(?<![A-Za-z0-9])(?:{alternatives})(?![A-Za-z0-9])")


_PATTERN = _build_pattern(READINGS)


def apply_readings(text: str, language: str) -> str:
    """ナレーションの固有名詞をカタカナの読みに置き換える。

    Args:
        text: ナレーション（原文）
        language: 言語コード。``ja`` 以外は何もしない——英語のボイスに
            カタカナを渡すと読めない

    Returns:
        str: 読みを当てた文字列。字幕には使わない（モジュールの docstring 参照）
    """
    if language != "ja":
        return text
    return _PATTERN.sub(lambda m: READINGS[m.group(0)], text)
